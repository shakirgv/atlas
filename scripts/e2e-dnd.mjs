// Drag a stop from the first day to the second day in the itinerary and verify it persisted.
import { chromium } from "playwright";
const BASE = "http://localhost:3000";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(`${BASE}/login`);
await page.fill("#email", "me@atlas.test");
await page.fill("#password", "atlas-dev-123");
await Promise.all([page.waitForURL(`${BASE}/`), page.click("button[type=submit]")]);
await page.goto(`${BASE}/itinerary`);
await page.waitForTimeout(1000);
const days = page.locator("article[aria-label^='Day']");
const before = [await days.nth(0).locator("li[id^=stop-]").count(), await days.nth(1).locator("li[id^=stop-]").count()];
const handle = days.nth(0).getByRole("button", { name: /^Drag / }).first();
const name = await handle.getAttribute("aria-label");
const target = days.nth(1).locator("li[id^=stop-]").first();
const hb = await handle.boundingBox();
const tb = await target.boundingBox();
await page.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2);
await page.mouse.down();
await page.mouse.move(hb.x + 10, hb.y + 20, { steps: 5 });
await page.mouse.move(tb.x + 60, tb.y + 10, { steps: 25 });
await page.waitForTimeout(300);
await page.mouse.up();
await page.waitForTimeout(2500);
await page.reload();
await page.waitForTimeout(1500);
const after = [await days.nth(0).locator("li[id^=stop-]").count(), await days.nth(1).locator("li[id^=stop-]").count()];
console.log(name, "before", before, "after reload", after, "errors", errors);
await browser.close();
